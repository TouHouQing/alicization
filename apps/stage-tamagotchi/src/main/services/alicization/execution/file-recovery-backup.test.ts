it('upgrades an existing database so each backup reference uses an indexed withdrawal lookup', async () => {
  const f = await createFileRecoveryTestFixture()
  try {
    const database = new DatabaseSync(f.db().dbPath)
    try { database.exec('DROP INDEX IF EXISTS idx_life_evidence_cleanup_source') }
    finally { database.close() }
    await f.reopen()
    const reader = await new Promise<InstanceType<typeof sqlite.Database>>((resolve, reject) => {
      const opened = new sqlite.Database(f.db().dbPath, sqlite.OPEN_READONLY, error => error ? reject(error) : resolve(opened))
    })
    try {
      const plan = await new Promise<Array<{ detail: string }>>((resolve, reject) => reader.all(`EXPLAIN QUERY PLAN ${fileRecoveryBackupReferencesSql}`, ['alice', 4097], (error, rows) => error ? reject(error) : resolve(rows as Array<{ detail: string }>)))
      // Three source expressions must be lookup keys, rather than scanning
      // every forgotten memory/version for every encrypted file reference.
      expect(plan.some(row => /j .*<expr>=\?.*<expr>=\?.*<expr>=\?/u.test(String(row.detail))), JSON.stringify(plan)).toBe(true)
      expect(plan.some(row => /i .*\(card_id=\? AND source=\?\)/u.test(row.detail)), JSON.stringify(plan)).toBe(true)
    }
    finally { await new Promise<void>((resolve, reject) => reader.close(error => error ? reject(error) : resolve())) }
  }
  finally { await f.close() }
})

it('budgets actual ciphertext references independently of thousands of creation-only version records', async () => {
  const f = await createFileRecoveryTestFixture()
  try {
    const path = join(f.root, 'actual-original.txt')
    await writeFile(path, 'actual private original')
    await f.save(path, 'actual generated file')
    const original = (await f.versions.list('alice')).entries[0]
    const record = await f.versions.read(original.id, 'alice')
    const snapshot = join(f.root, 'large-history-snapshot.db')
    await f.db().snapshotLifeDatabase(snapshot)
    const database = new DatabaseSync(snapshot)
    try {
      database.exec('BEGIN')
      const insert = database.prepare(`INSERT INTO life_ingress(card_id,ingress_id,kind,source,source_key,payload_hash,payload_ref_json,occurred_at,observed_at,status) VALUES(?,?,'tool-result','file-version-before',?,?,?,?,?,'settled')`)
      // A synthetic snapshot history exercises the production reader budget;
      // these creation-only records never dispatch filesystem operations.
      for (let index = 0; index < 4100; index++) {
        const effectId = `snapshot-creation:${index}`
        const versionId = executionDigest({ cardId: 'alice', effectId })
        const payload = { ...record.before, id: versionId, effectId, path: join(f.root, `created-${index}.txt`), existed: false, device: null, inode: null, bytes: 0, sha256: createHash('sha256').digest('hex'), blob: null }
        const raw = JSON.stringify(payload)
        insert.run('alice', `file-version-before:${versionId}`, versionId, createHash('sha256').update(raw).digest('hex'), raw, payload.at, payload.at)
      }
      database.exec('COMMIT')
    }
    finally { database.close() }
    expect(await readFileRecoveryBackupReferences(snapshot, 'alice')).toEqual([record.before.blob])
    expect(await readFile(path, 'utf8')).toBe('actual generated file')
  }
  finally { await f.close() }
}, 30000)

it.each(['missing-original-reference', 'missing-creation-field', 'nonobject-reference'] as const)('rejects malformed version metadata rather than silently omitting ciphertext: %s', async (failure) => {
  const f = await createFileRecoveryTestFixture()
  try {
    const path = join(f.root, 'original.txt')
    await writeFile(path, 'original private bytes')
    await f.save(path, 'generated bytes')
    const version = (await f.versions.list('alice')).entries[0]
    const record = await f.versions.read(version.id, 'alice')
    const snapshot = join(f.root, 'malformed-reference-snapshot.db')
    await f.db().snapshotLifeDatabase(snapshot)
    const payload: Record<string, unknown> = { ...record.before, blob: null }
    if (failure === 'missing-creation-field') {
      payload.existed = false
      delete payload.blob
    }
    if (failure === 'nonobject-reference')
      payload.blob = 'not-an-encrypted-reference'
    const raw = JSON.stringify(payload)
    const database = new DatabaseSync(snapshot)
    try { database.prepare('UPDATE life_ingress SET payload_ref_json=?,payload_hash=? WHERE card_id=? AND ingress_id=?').run(raw, createHash('sha256').update(raw).digest('hex'), 'alice', `file-version-before:${version.id}`) }
    finally { database.close() }
    await expect(readFileRecoveryBackupReferences(snapshot, 'alice')).rejects.toThrow()
    expect(await readFile(path, 'utf8')).toBe('generated bytes')
  }
  finally { await f.close() }
})

it('retains a pending orphan-cleanup audit through older identity restore and settles absence without replaying business writes', async () => {
  const f = await createFileRecoveryTestFixture()
  try {
    const path = join(f.root, 'business.txt')
    await writeFile(path, 'private before image')
    await f.save(path, 'current business result')
    const backupRuntime = createLifeBackupRuntime({ userDataPath: f.root, cardId: () => 'alice', snapshot: f.db().snapshotLifeDatabase, state: f.db().readLifeState, schema: async () => lifeSchemaVersion })
    const backup = await backupRuntime.create()
    const directory = join(dirname(f.db().dbPath), 'file-recovery')
    const orphan = join(directory, `${'e'.repeat(64)}.blob`)
    await writeFile(orphan, '')
    const time = new Date(Date.now() - 172800000)
    await utimes(orphan, time, time)
    const closedCodec = (): never => { throw new Error('Orphan cleanup must not decrypt') }
    const storage = () => createFileRecoveryVault({ root: directory, seal: closedCodec, unseal: closedCodec })
    const database = f.db()
    const wrapped = { ...database, commitLifeState: async (input: Parameters<typeof database.commitLifeState>[0], options?: Parameters<typeof database.commitLifeState>[1]) => {
      if (input.operationKey.startsWith('file-version-orphan:') && input.operationKey.endsWith(':observed'))
        throw new Error('injected orphan result failure')
      return database.commitLifeState(input, options)
    } }
    await expect(collectFileVersionOrphans({ database: wrapped, vault: storage(), assertCurrent: () => {} })).rejects.toThrow('orphan result failure')
    const prepared = (await database.readLifeIngressPage({ source: 'file-version-orphan-cleanup' })).entries[0]
    expect(prepared.status).toBe('held')
    await expect(stat(orphan)).rejects.toMatchObject({ code: 'ENOENT' })
    await backupRuntime.requestRestore(backup.id, backup.manifestHash)
    await f.reopen(() => applyPendingLifeRestore(f.root))
    expect(await f.db().getLifeIngress(prepared.id)).toEqual(prepared)
    expect(await collectFileVersionOrphans({ database: f.db(), vault: storage(), assertCurrent: () => {} })).toEqual({ inspected: 1, removed: 0 })
    const settled = await f.db().readLifeIngressPage({ source: 'file-version-orphan-cleanup' })
    expect(settled.entries).toHaveLength(2)
    expect(settled.entries.every(entry => entry.status === 'settled')).toBe(true)
    expect(await readFile(path, 'utf8')).toBe('current business result')
  }
  finally { await f.close() }
}, 30000)

it('retains the explicit host takeover and original unknown receipt instead of reviving it after identity restore', async () => {
  const f = await createFileRecoveryTestFixture()
  const host = createHostFileRecoveryControl({ database: f.databasePort, versions: () => f.versions, broker: f.broker, otherWritersStopped: () => true, inspectNativeProcess: process => controlFileRecoveryProcess('inspect', process), stopNativeProcess: async process => await controlFileRecoveryProcess('stop', process) === 'stopped' ? 'stopped' : 'unknown' })
  try {
    const path = join(f.root, 'taken-over.txt')
    await writeFile(path, 'private original')
    await f.save(path, 'generated')
    const backupRuntime = createLifeBackupRuntime({ userDataPath: f.root, cardId: () => 'alice', snapshot: f.db().snapshotLifeDatabase, state: f.db().readLifeState, schema: async () => lifeSchemaVersion })
    const backup = await backupRuntime.create()
    const version = (await f.versions.list('alice')).entries[0]
    const database = f.db()
    f.database({ ...database, commitLifeState: async (input, options) => {
      if (input.operationKey.startsWith('file-recovery-audit:') && input.operationKey.endsWith(':observed'))
        throw new Error('synthetic result audit failure')
      return database.commitLifeState(input, options)
    } })
    const preview = await host.preview('alice', version.id, 7)
    await expect(host.restore('alice', version.id, preview.token!, 7)).rejects.toThrow('result audit failure')
    const effectId = (await host.list('alice')).entries[0].recoveryEffectIds[0]
    const control = createHostEffectControl({ database: f.databasePort, broker: f.broker, writerStopped: effect => host.nativeStopped('alice', effect.id) })
    const confirmation = await control({ cardId: 'alice', effectId, action: 'preview' }, 7)
    if (confirmation.state !== 'preview')
      throw new Error('Expected actual takeover confirmation')
    await control({ cardId: 'alice', effectId, action: 'takeover', token: confirmation.token, confirmedStopped: true }, 7)
    const originalId = `host-takeover-original:${confirmation.token}`
    const decisionId = `host-takeover:${confirmation.token}`
    const original = await database.getLifeIngress(originalId)
    const decision = await database.getLifeIngress(decisionId)
    expect(original).not.toBeNull()
    await backupRuntime.requestRestore(backup.id, backup.manifestHash)
    await host.dispose()
    await f.reopen(() => applyPendingLifeRestore(f.root))
    expect(await f.db().getLifeIngress(originalId)).toEqual(original)
    expect(await f.db().getLifeIngress(decisionId)).toEqual(decision)
    expect(await f.db().getLifeEffect(effectId)).toMatchObject({ status: 'failed', receipt: { outcome: 'host-taken-over', output: { sideEffectState: 'unknown' } } })
    expect(await readFile(path, 'utf8')).toBe('private original')
  }
  finally { await host.dispose(); await f.close() }
}, 30000)

it.each(['staged', 'before-moved'] as const)('retains snapshot and newer operational ciphertext through interrupted %s identity restore', async (phase) => {
  const f = await createFileRecoveryTestFixture()
  try {
    const path = join(f.root, 'actual-report.txt')
    await writeFile(path, 'private original before snapshot')
    const first = await f.save(path, 'first generated report')
    const runtime = createLifeBackupRuntime({ userDataPath: f.root, cardId: () => 'alice', snapshot: f.db().snapshotLifeDatabase, state: f.db().readLifeState, schema: async () => lifeSchemaVersion })
    const backup = await runtime.create()
    const backupDirectory = join(f.root, 'alicizations/life-backups', backup.id)
    const manifest = JSON.parse(await readFile(join(backupDirectory, 'manifest.json'), 'utf8'))
    expect(manifest.format).toBe('life-backup-v2')
    expect(manifest.fileRecovery).toHaveLength(1)
    expect(await readdir(join(backupDirectory, 'file-recovery'))).toHaveLength(1)
    expect((await readFile(join(backupDirectory, 'file-recovery', `${manifest.fileRecovery[0].id}.blob`))).includes(Buffer.from('private original before snapshot'))).toBe(false)
    expect(JSON.stringify(backup)).not.toContain('cipherSha256')
    const second = await f.save(path, 'second generated report')
    const versions = (await f.versions.list('alice')).entries
    await runtime.requestRestore(backup.id, backup.manifestHash)
    await f.reopen(async () => {
      await expect(applyPendingLifeRestore(f.root, (current) => {
        if (current === phase)
          throw new Error('synthetic power loss')
      })).rejects.toThrow('synthetic power loss')
      await applyPendingLifeRestore(f.root)
    })
    expect(await readFile(path, 'utf8')).toBe('second generated report')
    expect(await readdir(join(dirname(f.db().dbPath), 'file-recovery'))).toHaveLength(2)
    for (const version of versions) {
      const original = await f.versions.original(version.id, 'alice')
      expect(original.bytes?.toString()).toBe(version.effectId === first ? 'private original before snapshot' : 'first generated report')
      expect((await f.db().getLifeEffect(version.effectId))?.status).toBe('uncertain')
    }
    expect(versions.some(version => version.effectId === second)).toBe(true)
    expect(await applyPendingLifeRestore(f.root)).toBeNull()
  }
  finally { await f.close() }
})

it.each(['missing', 'changed', 'legacy-with-references'] as const)('refuses %s ciphertext before requesting destructive restore', async (failure) => {
  const f = await createFileRecoveryTestFixture()
  try {
    const path = join(f.root, 'report.txt')
    await writeFile(path, 'original bytes')
    await f.save(path, 'generated bytes')
    const runtime = createLifeBackupRuntime({ userDataPath: f.root, cardId: () => 'alice', snapshot: f.db().snapshotLifeDatabase, state: f.db().readLifeState, schema: async () => lifeSchemaVersion })
    const backup = await runtime.create()
    const directory = join(f.root, 'alicizations/life-backups', backup.id)
    const manifestPath = join(directory, 'manifest.json')
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
    const cipher = join(directory, 'file-recovery', `${manifest.fileRecovery[0].id}.blob`)
    let expected = backup.manifestHash
    if (failure === 'missing') {
      await unlink(cipher)
    }
    else if (failure === 'changed') {
      await writeFile(cipher, 'wrong ciphertext')
    }
    else {
      manifest.format = 'life-backup-v1'
      delete manifest.fileRecovery
      const raw = JSON.stringify(manifest)
      await writeFile(manifestPath, raw)
      expected = createHash('sha256').update(raw).digest('hex')
    }
    await expect(runtime.requestRestore(backup.id, expected)).rejects.toThrow()
    expect(await readFile(path, 'utf8')).toBe('generated bytes')
    expect(await applyPendingLifeRestore(f.root)).toBeNull()
  }
  finally { await f.close() }
})
