/* eslint-disable unicorn/prefer-dom-node-text-content -- Assert text visible in the actual product. */
const assert = require('node:assert/strict')

const { sampleLive2D } = require('./live2d-product-checks.cjs')

exports.runPersonaGrowthProductChecks = async function ({ stage, settings, chat, report, capture, check, click }) {
  report.scope = 'real-background-Live2D-growth-UI-and-model-turn-with-explicit-synthetic-historical-evidence'
  await settings.goto(`${settings.url().split('#')[0]}#/settings/life`)
  const region = settings.getByTestId('persona-growth')
  const item = region.locator('article').filter({ hasText: '专注工作时先留出思考空间' })
  await item.waitFor()
  await click(item.getByRole('button', { name: '查看记忆与来源', exact: true }))
  await item.getByText('第1次测试经历：用户专注时先留出思考空间，在停顿后自然接话。', { exact: true }).waitFor()
  check('Growth sources show actual owned local excerpts instead of a generic memory link', await item.locator('time').count() === 3)
  await capture(settings, 'persona-growth-sources')
  await click(region.getByRole('button', { name: '继续适应', exact: true }))
  await region.getByRole('button', { name: '暂停适应', exact: true }).waitFor()
  const before = await chat.locator('[data-chat-message-role="assistant"]').count()
  await chat.locator('textarea').fill('刚完成一段代码，终于把那个编译问题解决了。现在停下来，想和你轻松聊两句。')
  await click(chat.getByRole('button', { name: '发送消息', exact: true }))
  await chat.waitForFunction(count => document.querySelectorAll('[data-chat-message-role="assistant"]').length > count, before, { timeout: 90000 })
  await chat.getByRole('button', { name: '发送消息', exact: true }).waitFor({ timeout: 90000 })
  report.personaGrowthDialogue = await chat.locator('[data-chat-message-role="assistant"]').last().innerText()
  check('A real configured-model turn completes while the scoped habit is on trial', report.personaGrowthDialogue.trim().length > 0)
  await settings.reload()
  await item.getByText('正在尝试', { exact: false }).waitFor()
  await click(region.getByRole('button', { name: '暂停适应', exact: true }))
  await region.getByRole('button', { name: '继续适应', exact: true }).waitFor()
  await click(item.getByRole('button', { name: '补充例外', exact: true }))
  await item.getByRole('textbox').fill('用户明确说想聊天时，可以直接回应')
  await click(item.getByRole('button', { name: '保存并重新观察', exact: true }))
  await item.getByText('用户明确说想聊天时，可以直接回应', { exact: true }).waitFor()
  check('Correction restarts observation without carrying old trial success', (await item.innerText()).includes('0 次独立经历') && (await item.innerText()).includes('仍在探索'))
  await capture(settings, 'persona-growth-corrected')
  await settings.reload()
  await item.getByText('用户明确说想聊天时，可以直接回应', { exact: true }).waitFor()
  check('Correction and pause survive a real renderer reload', await region.getByRole('button', { name: '继续适应', exact: true }).isVisible())
  const first = await sampleLive2D(stage)
  await click(item.getByRole('button', { name: '撤回这项认识', exact: true }))
  await region.getByText('还没有足够的独立经历形成新的习惯。', { exact: true }).waitFor()
  assert.equal(await region.locator('article').count(), 0)
  const second = await sampleLive2D(stage)
  check('Growth changes preserve actual Live2D final drawing', first.models.length === 1 && second.models.length === 1 && second.models[0].drawFrame.frame > first.models[0].drawFrame.frame)
  check('Withdrawn personality disappears from the real product', true)
  await capture(settings, 'persona-growth-withdrawn')
  check('Growth commands expose no inline error', await region.getByRole('alert').count() === 0)
}
