const assert = require('node:assert/strict')
const { createHash, randomUUID } = require('node:crypto')
const fs = require('node:fs/promises')
const path = require('node:path')

const { sampleLive2D } = require('./live2d-product-checks.cjs')

const hash = value => createHash('sha256').update(value).digest('hex')

exports.runLifeBackupProductChecks = async function ({ settings, stage, report, root, check, click, capture }) {
  assert.equal(report.syntheticIdentity, true)
  const profile = await fs.realpath(report.profile)
  assert.ok(path.basename(profile).startsWith('alicization-life-product-regression-'))
  const directory = path.join(profile, 'alicizations', 'life-backups')
  const entries = async () => (await fs.readdir(directory)).filter(name => /^[a-f\d]{8}(?:-[a-f\d]{4}){3}-[a-f\d]{12}$/u.test(name))
  await settings.goto(`${settings.url().split('#')[0]}#/settings/life`)
  await settings.getByRole('button', { name: '保存交流节奏', exact: true }).waitFor()
  const section = settings.locator('details').filter({ has: settings.locator('summary').filter({ hasText: '本地备份与恢复' }) })
  if (!await section.evaluate(node => node.open))
    await click(section.locator('summary'))
  const create = section.getByRole('button', { name: '创建备份', exact: true })
  const list = section.getByRole('button', { name: '查看备份', exact: true })
  const waitForList = () => settings.waitForFunction(() => [...document.querySelectorAll('button')].some(node => node.textContent.trim() === '查看备份' && !node.disabled))
  const restore = section.getByRole('button', { name: '恢复此备份', exact: true })
  await click(create)
  await restore.first().waitFor()
  await list.waitFor({ state: 'visible' })
  const first = await entries()
  assert.equal(first.length, 1)
  const valid = path.join(directory, first[0])
  const validManifest = await fs.readFile(path.join(valid, 'manifest.json'))
  const validSnapshotHash = hash(await fs.readFile(path.join(valid, 'alicization.db')))
  const manifest = JSON.parse(validManifest.toString('utf8'))
  const soul = path.join(profile, 'alicizations', 'cards', manifest.cardId, 'SOUL.md')
  const soulHash = hash(await fs.readFile(soul))
  await click(create)
  await settings.waitForFunction(() => [...document.querySelectorAll('button')].filter(node => node.textContent.trim() === '恢复此备份').length === 2)
  const damagedId = (await entries()).find(id => id !== first[0])
  assert.ok(damagedId)
  const damagedPath = path.join(directory, damagedId, 'manifest.json')
  const original = await fs.readFile(damagedPath, 'utf8')
  await fs.writeFile(path.join(root, 'backup-original-manifest.json'), original, { flag: 'wx' })
  const content = JSON.parse(original)
  check('Two backups are created and listed through the actual settings IPC', await restore.count() === 2 && manifest.cardId === 'default')
  const warning = section.locator('[data-life-backup-issues]')
  report.backupExperiences = []
  for (const condition of ['invalid-json', 'oversized', 'wrong-identity', 'unsupported-format']) {
    const damaged = condition === 'invalid-json' ? '{unreadable' : condition === 'oversized' ? ' '.repeat(2 * 1024 * 1024 + 1) : JSON.stringify({ ...content, ...(condition === 'wrong-identity' ? { id: randomUUID() } : { format: 'life-backup-future-unreadable' }) })
    await fs.writeFile(damagedPath, damaged)
    await click(list)
    await waitForList()
    await warning.waitFor()
    await settings.waitForFunction(() => [...document.querySelectorAll('button')].filter(node => node.textContent.trim() === '恢复此备份').length === 1)
    check(`${condition}: the other exact backup remains available`, await restore.count() === 1 && (await warning.textContent()).includes('备份文件已保留'))
    check(`${condition}: unreadable metadata is retained without rewriting either original backup`, await fs.readFile(damagedPath, 'utf8') === damaged && (await fs.readFile(path.join(valid, 'manifest.json'))).equals(validManifest) && hash(await fs.readFile(path.join(valid, 'alicization.db'))) === validSnapshotHash)
    check(`${condition}: current personality remains intact and the page has no uncaught error`, hash(await fs.readFile(soul)) === soulHash && await settings.getByRole('alert').count() === 0)
    await capture(settings, `backup-${condition}`)
    report.backupExperiences.push({ condition, retained: true, otherBackupAvailable: true, personalityPreserved: true })
  }
  // A host can repair local metadata; re-list must recover without restarting.
  await fs.writeFile(damagedPath, original)
  await click(list)
  await waitForList()
  await warning.waitFor({ state: 'detached' })
  check('Repairing the synthetic metadata restores both rows on refresh', await restore.count() === 2)
  const body = await sampleLive2D(stage)
  check('Backup maintenance retains the actual Live2D model', body.models.length === 1 && body.models[0].parameterSampling === 'final-draw')
  await capture(settings, 'backup-repaired')
}
